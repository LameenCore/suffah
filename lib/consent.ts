// Parental consent for minors (Law 25 — T36 schema, T37 flow).
//
// consent_records (migration 0011) is append-only: every decision is a new row.
// "Active" consent for a child = the most recent row for the CURRENT version
// with granted = true. Bump CONSENT_VERSION whenever a purpose below changes
// materially — old rows then no longer count as active and the guardian is
// re-prompted.

import { getServiceClient } from "@/lib/db";

